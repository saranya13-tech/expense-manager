"""Progressive Web App endpoints: manifest, service worker and offline page.

The service worker lives at /sw.js (site root) so it can control every page.
It never caches pages or API data (they contain private financial info) —
only static assets and the offline fallback page.
"""
import hashlib
import json

from django.http import HttpResponse, JsonResponse
from django.shortcuts import render
from django.templatetags.static import static
from django.views.decorators.cache import cache_control
from django.views.decorators.http import require_GET

APP_NAME = "Spendly"
THEME_COLOR = "#ffffff"
BACKGROUND_COLOR = "#f5f6fa"


def _precache_urls():
    return [
        "/offline/",
        static("tracker/app.css"),
        static("tracker/icon-192.png"),
        static("tracker/icon-512.png"),
        static("tracker/icon-180.png"),
    ]


@require_GET
@cache_control(max_age=3600)
def manifest(request):
    icons = []
    for size in (192, 512):
        src = static(f"tracker/icon-{size}.png")
        icons.append({"src": src, "sizes": f"{size}x{size}", "type": "image/png", "purpose": "any"})
        icons.append({"src": src, "sizes": f"{size}x{size}", "type": "image/png", "purpose": "maskable"})
    data = {
        "id": "/",
        "name": APP_NAME,
        "short_name": APP_NAME,
        "description": "Track balance, income and expenses across separate books.",
        "start_url": "/",
        "scope": "/",
        "display": "standalone",
        "orientation": "portrait",
        "background_color": BACKGROUND_COLOR,
        "theme_color": THEME_COLOR,
        "categories": ["finance", "productivity"],
        "icons": icons,
        "shortcuts": [{"name": "My books", "url": "/", "icons": [{"src": static("tracker/icon-192.png"), "sizes": "192x192"}]}],
    }
    return JsonResponse(data, content_type="application/manifest+json", json_dumps_params={"indent": 2})


SERVICE_WORKER = """\
// Spendly service worker. Generated by tracker/pwa.py.
const CACHE = 'spendly-%(version)s';
const OFFLINE_URL = '/offline/';
const PRECACHE = %(precache)s;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('spendly-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Pages: always go to the network (never cache private data); show the offline page if it fails.
  if (req.mode === 'navigate') {
    event.respondWith(fetch(req).catch(() => caches.match(OFFLINE_URL)));
    return;
  }

  // Static files have content hashes in their names, so cache-first is safe.
  if (url.pathname.startsWith('/static/')) {
    event.respondWith(
      caches.match(req).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(req, copy));
        }
        return res;
      }))
    );
  }
  // Everything else (API, forms) passes straight through to the network.
});
"""


@require_GET
def service_worker(request):
    precache = _precache_urls()
    # New static file hashes => new cache version => old caches are cleaned up on activate.
    version = hashlib.sha256("|".join(precache).encode()).hexdigest()[:10]
    js = SERVICE_WORKER % {"version": version, "precache": json.dumps(precache)}
    response = HttpResponse(js, content_type="application/javascript")
    response["Cache-Control"] = "no-cache"
    response["Service-Worker-Allowed"] = "/"
    return response


@require_GET
def offline(request):
    return render(request, "tracker/offline.html", {"app_name": APP_NAME})
